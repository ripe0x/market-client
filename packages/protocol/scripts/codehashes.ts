// Deploys the pinned protocol on a throwaway Anvil and writes src/codehashes.ts with each
// contract's runtime code hash. CREATE2 with fixed constructor arguments gives identical runtime
// code on every chain, so these hashes must match Sepolia and mainnet deployments.
import { writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { keccak256 } from "viem";
import { startChain } from "../devchain";

const c = await startChain({ collections: false });
const d = c.deployment;
const names = ["market", "orderImplementation", "feeConfig", "nftSale", "nftBid"] as const;
let out = "// Generated by scripts/codehashes.ts. Do not edit.\nexport const codehash = {\n";
for (const n of names) out += `  ${n}: "${keccak256((await c.pub.getCode({ address: d[n] }))!)}",\n`;
out += "} as const;\n";
writeFileSync(resolve(import.meta.dirname, "../src/codehashes.ts"), out);
c.stop();
console.log(out);
