// Writes src/abis.ts from the pinned protocol build (contracts/market/out) and
// devchain/artifacts.ts from the client's test collections. Run after `pnpm build:contracts`.
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const root = resolve(import.meta.dirname, "../../..");
const art = (dir: string, file: string, name: string) =>
  JSON.parse(readFileSync(resolve(root, dir, "out", file, `${name}.json`), "utf8"));

const protocol: [string, string, string][] = [
  ["marketAbi", "Market.sol", "Market"],
  ["orderAbi", "Order.sol", "Order"],
  ["nftSaleAbi", "NFTSale.sol", "NFTSale"],
  ["nftBidAbi", "NFTBid.sol", "NFTBid"],
  ["feeConfigAbi", "FeeConfig.sol", "FeeConfig"],
  ["erc721ErrorsAbi", "draft-IERC6093.sol", "IERC721Errors"],
];
let out = "// Generated by scripts/gen-abis.ts from contracts/market (ripe0x/market). Do not edit.\n\n";
for (const [name, file, contract] of protocol) {
  out += `export const ${name} = ${JSON.stringify(art("contracts/market", file, contract).abi)} as const;\n\n`;
}
writeFileSync(resolve(import.meta.dirname, "../src/abis.ts"), out);

const test = ["TestNFT", "PlainNFT", "LockableNFT", "ZeroReceiverRoyaltyNFT", "RefusingReceiver", "Test1155", "FakeSoldEmitter", "RogueCloneFactory"];
let t = "// Generated by scripts/gen-abis.ts from contracts/test-collections. Do not edit.\n\n";
for (const c of test) {
  const a = art("contracts/test-collections", "TestCollections.sol", c);
  t += `export const ${c} = { abi: ${JSON.stringify(a.abi)} as const, bytecode: ${JSON.stringify(a.bytecode.object)} as \`0x\${string}\` };\n\n`;
}
writeFileSync(resolve(import.meta.dirname, "../devchain/artifacts.ts"), t);
console.log("wrote src/abis.ts and devchain/artifacts.ts");
